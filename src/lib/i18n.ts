export type TranslationKey = keyof typeof translations.en;

export const translate = (
  language: PlantieLanguage | null | undefined,
  key: TranslationKey | string,
  replacements: Record<string, string | number> = {},
) => {
  const dictionary = translations[language ?? defaultLanguage] ?? translations[defaultLanguage];
  const template = dictionary[key] ?? translations[defaultLanguage][key] ?? key;
  return Object.entries(replacements).reduce(
    (value, [token, replacement]) => value.split(`{${token}}`).join(String(replacement)),
    template,
  );
};

export const createTranslator =
  (language: PlantieLanguage | null | undefined) =>
  (key: TranslationKey | string, replacements?: Record<string, string | number>) =>
    translate(language, key, replacements);
